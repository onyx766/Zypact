#!/usr/bin/env tsx
/**
 * Static contract assertions over migration 0030.
 *
 * These read the migration as text. They prove the SQL *says* what the
 * design requires — they do not execute PostgreSQL.
 *
 * No database, network, or migration execution occurs here.
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";

const MIGRATION = join(
  process.cwd(),
  "supabase/migrations/0030_snapshot_request_worker_claim.sql"
);

const sql = readFileSync(MIGRATION, "utf-8");
const normalized = sql.replace(/\s+/g, " ").toLowerCase();

let passed = 0;
let failed = 0;

function check(name: string, condition: boolean, detail = ""): void {
  if (condition) {
    passed += 1;
    console.log(`  ✓ ${name}`);
  } else {
    failed += 1;
    console.log(`  ✗ ${name}${detail ? ` — ${detail}` : ""}`);
  }
}

function has(fragment: string): boolean {
  return normalized.includes(fragment.replace(/\s+/g, " ").toLowerCase());
}

console.log("\nColumns");
for (const column of [
  "add column if not exists claimed_by text null",
  "add column if not exists claim_token uuid null",
  "add column if not exists lease_expires_at timestamptz null",
  "add column if not exists attempt_count integer not null default 0",
]) {
  check(column, has(column));
}

console.log("\nConstraints");
check(
  "attempt_count non-negative constraint",
  has("snapshot_requests_attempt_count_check") &&
    has("check (attempt_count >= 0)")
);
check(
  "claimed_by length constraint (1-100)",
  has("snapshot_requests_claimed_by_length_check") &&
    has("char_length(claimed_by) between 1 and 100")
);
check(
  "ownership coherence constraint (all null or all non-null)",
  has("snapshot_requests_claim_coherence_check") &&
    has(
      "claimed_by is null and claim_token is null and lease_expires_at is null"
    ) &&
    has(
      "claimed_by is not null and claim_token is not null and lease_expires_at is not null"
    )
);

console.log("\nIndex");
check(
  "partial stale-lease index on (lease_expires_at, created_at)",
  has("snapshot_requests_stale_lease_idx") &&
    has("(lease_expires_at, created_at)") &&
    has("where status = 'running' and claim_token is not null")
);

console.log("\nInternal project helper");
check(
  "_ensure_snapshot_request_project exists and returns uuid",
  has("public._ensure_snapshot_request_project( p_request_id uuid ) returns uuid")
);
check(
  "helper has no execute grant to any role",
  !/grant\s+execute\s+on\s+function\s+public\._ensure_snapshot_request_project/i.test(
    sql
  )
);
check(
  "helper execution revoked from service_role",
  /revoke\s+all\s+on\s+function\s+public\._ensure_snapshot_request_project\(uuid\)\s+from\s+service_role/i.test(
    sql
  )
);
check(
  "helper does not transition status",
  !/_ensure_snapshot_request_project[\s\S]*?\$\$;/i
    .exec(sql)?.[0]
    ?.includes("status =") ?? false
);

console.log("\nManual reservation RPC");
check(
  "reserve_snapshot_request_project is replaced",
  has(
    "create or replace function public.reserve_snapshot_request_project( p_request_id uuid )"
  )
);
check(
  "reserve refuses worker-owned running rows",
  has(
    "if v_request.status = 'running' and v_request.claim_token is not null then return; end if;"
  )
);
check(
  "reserve delegates to the shared helper",
  has("v_project_id := public._ensure_snapshot_request_project(p_request_id)")
);

console.log("\nClaim RPC");
check(
  "claim_next_snapshot_request signature",
  has(
    "public.claim_next_snapshot_request( p_worker_id text, p_lease_seconds integer, p_max_attempts integer ) returns setof public.snapshot_requests"
  )
);
check("FOR UPDATE SKIP LOCKED is used", has("for update skip locked"));
check("candidate selection is limited to one row", has("limit 1"));
check(
  "claim token generated by gen_random_uuid()",
  has("v_token := gen_random_uuid()")
);
check(
  "claim RPC takes no caller-supplied token",
  !/claim_next_snapshot_request\([^)]*token[^)]*\)/i.test(sql)
);
check(
  "stale-at-max terminalization to failed",
  has("set status = 'failed'") &&
    has("and attempt_count >= p_max_attempts")
);
check(
  "terminalization clears ownership fields",
  has(
    "set status = 'failed', claimed_by = null, claim_token = null, lease_expires_at = null"
  )
);
check(
  "terminalization excludes manual runs",
  has("where status = 'running' and claim_token is not null and lease_expires_at <= now()")
);
check(
  "stale requests ordered before queued",
  has("case when request.status = 'running' then 0 else 1 end")
);
check(
  "oldest-first with deterministic id tie-breaker",
  has("request.created_at asc, request.id asc")
);
check(
  "queued claims set progress_stage to reserved",
  has("when snapshot_requests.status = 'queued' then 'reserved'")
);
check(
  "stale claims preserve progress_stage",
  has("else snapshot_requests.progress_stage")
);
check(
  "attempt_count increments on claim",
  has("attempt_count = snapshot_requests.attempt_count + 1")
);
check(
  "report_ready and failed are not eligible",
  !has("request.status = 'report_ready'") && !has("or request.status = 'failed'")
);

console.log("\nRenew RPC");
check(
  "renew_snapshot_request_lease signature",
  has(
    "public.renew_snapshot_request_lease( p_request_id uuid, p_claim_token uuid, p_lease_seconds integer ) returns setof public.snapshot_requests"
  )
);
check(
  "renewal checks the claim token",
  has("v_request.claim_token <> p_claim_token")
);
check(
  "renewal requires an unexpired lease",
  has("v_request.lease_expires_at <= now()") &&
    has("and lease_expires_at > now()")
);
check(
  "renewal extends from now(), not the previous expiry",
  has("set lease_expires_at = now() + make_interval(secs => p_lease_seconds)")
);

console.log("\nSecurity");
const publicRpcs = [
  "reserve_snapshot_request_project(uuid)",
  "claim_next_snapshot_request(text, integer, integer)",
  "renew_snapshot_request_lease(uuid, uuid, integer)",
];
check(
  "every function is security definer",
  (sql.match(/security definer/gi) ?? []).length === 4,
  `found ${(sql.match(/security definer/gi) ?? []).length}, expected 4`
);
check(
  "every function sets an explicit search_path",
  (sql.match(/set search_path = public, pg_temp/gi) ?? []).length === 4
);
for (const rpc of publicRpcs) {
  const esc = rpc.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  check(
    `${rpc.split("(")[0]}: revoked from public/anon/authenticated`,
    ["public", "anon", "authenticated"].every((role) =>
      new RegExp(
        `revoke\\s+all\\s+on\\s+function\\s+public\\.${esc}\\s+from\\s+${role}`,
        "i"
      ).test(sql.replace(/\s+/g, " "))
    )
  );
  check(
    `${rpc.split("(")[0]}: execute granted to service_role only`,
    new RegExp(
      `grant\\s+execute\\s+on\\s+function\\s+public\\.${esc}\\s+to\\s+service_role`,
      "i"
    ).test(sql.replace(/\s+/g, " "))
  );
}

console.log("\nInput validation");
for (const [name, fragment] of [
  ["worker id range", "char_length(v_worker_id) < 1 or char_length(v_worker_id) > 100"],
  ["lease seconds range", "p_lease_seconds < 60 or p_lease_seconds > 3600"],
  ["max attempts range", "p_max_attempts < 1 or p_max_attempts > 10"],
] as Array<[string, string]>) {
  check(`${name} validated`, has(fragment));
}
check(
  "invalid input raises SQLSTATE 22023",
  (sql.match(/errcode = '22023'/g) ?? []).length >= 4
);

console.log("\n─────────────────────────────────────────────────────────");
console.log(
  "LIMITATION: Static SQL assertions do not prove PostgreSQL locking or"
);
console.log(
  "transaction behavior. FOR UPDATE SKIP LOCKED, row-lock contention, and"
);
console.log(
  "concurrent claim isolation remain unproven until Level 2 validation"
);
console.log("runs against a real PostgreSQL instance.");
console.log("─────────────────────────────────────────────────────────");

console.log(`\n${passed} passed, ${failed} failed`);
if (failed > 0) process.exit(1);
